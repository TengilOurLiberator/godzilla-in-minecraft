package dev.godzilla.client.mothra;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * Mothra's body: thorax with a fur collar, head with big compound eyes and feathered antennae, a tapering banded abdomen and
 * six short legs. Units are 1/16 of a model block; the renderer scales the whole model by 8 so one unit is half a block (the
 * body is about 24 blocks long). Model space is vanilla's (y down, front at -z); the renderer flips it. The texture is generated by
 * tools/mothra/make_textures.py and every texOffs below must match its region table. The wings are not part of this model: they
 * are bent surfaces drawn by the renderer.
 */
public class MothraModel extends EntityModel<MothraRenderState> {
	private final ModelPart abd1, abd2, abd3, tip, head;
	private final ModelPart antL, antR, legL1, legL2, legL3, legR1, legR2, legR3;

	public MothraModel(ModelPart root) {
		super(root);
		ModelPart thorax = root.getChild("thorax");
		this.head = thorax.getChild("head");
		this.abd1 = thorax.getChild("abd1");
		this.abd2 = abd1.getChild("abd2");
		this.abd3 = abd2.getChild("abd3");
		this.tip = abd3.getChild("tip");
		this.antL = head.getChild("antenna_l");
		this.antR = head.getChild("antenna_r");
		this.legL1 = thorax.getChild("leg_l1");
		this.legL2 = thorax.getChild("leg_l2");
		this.legL3 = thorax.getChild("leg_l3");
		this.legR1 = thorax.getChild("leg_r1");
		this.legR2 = thorax.getChild("leg_r2");
		this.legR3 = thorax.getChild("leg_r3");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition thorax = root.addOrReplaceChild("thorax",
				CubeListBuilder.create().texOffs(0, 0).addBox(-6F, -5F, -6F, 12F, 10F, 12F)
						.texOffs(64, 36).addBox(-4F, -8F, -5F, 8F, 3F, 8F),
				PartPose.ZERO);
		PartDefinition head = thorax.addOrReplaceChild("head",
				CubeListBuilder.create().texOffs(0, 24).addBox(-4F, -4F, -8F, 8F, 8F, 8F)
						.texOffs(0, 111).addBox(-5.5F, -4.5F, -1F, 11F, 9F, 2F),
				PartPose.offset(0F, 0F, -6F));
		head.addOrReplaceChild("eye_l", CubeListBuilder.create().texOffs(0, 42).addBox(-1.5F, -2.5F, -2.5F, 3F, 5F, 5F), PartPose.offset(4.6F, -0.5F, -3.5F));
		head.addOrReplaceChild("eye_r", CubeListBuilder.create().texOffs(0, 42).mirror().addBox(-1.5F, -2.5F, -2.5F, 3F, 5F, 5F), PartPose.offset(-4.6F, -0.5F, -3.5F));
		PartDefinition al = head.addOrReplaceChild("antenna_l",
				CubeListBuilder.create().texOffs(64, 0).addBox(-0.5F, -0.5F, -10F, 1F, 1F, 10F)
						.texOffs(64, 12).addBox(-1.5F, -0.5F, -9.5F, 3F, 1F, 9F),
				PartPose.offsetAndRotation(2F, -3.5F, -7F, -0.55F, -0.35F, 0F));
		head.addOrReplaceChild("antenna_r",
				CubeListBuilder.create().texOffs(64, 0).mirror().addBox(-0.5F, -0.5F, -10F, 1F, 1F, 10F)
						.texOffs(64, 12).mirror().addBox(-1.5F, -0.5F, -9.5F, 3F, 1F, 9F),
				PartPose.offsetAndRotation(-2F, -3.5F, -7F, -0.55F, 0.35F, 0F));
		PartDefinition abd1 = thorax.addOrReplaceChild("abd1",
				CubeListBuilder.create().texOffs(0, 54).addBox(-5F, -4F, 0F, 10F, 8F, 8F), PartPose.offset(0F, 1F, 6F));
		PartDefinition abd2 = abd1.addOrReplaceChild("abd2",
				CubeListBuilder.create().texOffs(0, 72).addBox(-4F, -3F, 0F, 8F, 6F, 8F), PartPose.offset(0F, 0.5F, 8F));
		PartDefinition abd3 = abd2.addOrReplaceChild("abd3",
				CubeListBuilder.create().texOffs(0, 88).addBox(-3F, -2.5F, 0F, 6F, 5F, 8F), PartPose.offset(0F, 0.5F, 8F));
		abd3.addOrReplaceChild("tip", CubeListBuilder.create().texOffs(0, 103).addBox(-1.5F, -1F, 0F, 3F, 2F, 4F), PartPose.offset(0F, 0.5F, 8F));
		for (int i = 0; i < 3; i++) {
			float z = -3F + i * 3F;
			thorax.addOrReplaceChild("leg_l" + (i + 1), CubeListBuilder.create().texOffs(64, 24).addBox(-1F, 0F, -1F, 2F, 8F, 2F),
					PartPose.offsetAndRotation(3.5F, 4.5F, z, 0F, 0F, -0.35F));
			thorax.addOrReplaceChild("leg_r" + (i + 1), CubeListBuilder.create().texOffs(64, 24).mirror().addBox(-1F, 0F, -1F, 2F, 8F, 2F),
					PartPose.offsetAndRotation(-3.5F, 4.5F, z, 0F, 0F, 0.35F));
		}
		return LayerDefinition.create(mesh, 128, 128);
	}

	@Override
	public void setupAnim(MothraRenderState s) {
		super.setupAnim(s);
		float p = s.phase;
		float curl = s.fold * 0.35F;
		abd1.xRot = (float) Math.sin(p - 0.6) * 0.07F * s.amp + curl * 0.3F;
		abd2.xRot = (float) Math.sin(p - 1.1) * 0.09F * s.amp + curl * 0.5F;
		abd3.xRot = (float) Math.sin(p - 1.6) * 0.11F * s.amp + curl * 0.7F;
		tip.xRot = (float) Math.sin(p - 2.1) * 0.12F * s.amp + curl * 0.7F;
		head.xRot = (float) Math.sin(p - 0.2) * 0.04F;
		float wag = (float) Math.sin(s.ageInTicks * 0.13F) * 0.12F;
		antL.yRot = -0.35F + wag;
		antR.yRot = 0.35F - wag;
		antL.xRot = -0.55F + (float) Math.sin(p) * 0.05F;
		antR.xRot = -0.55F + (float) Math.sin(p) * 0.05F;
		float dangle = 0.15F + s.fold * 0.5F;
		legL1.xRot = dangle + (float) Math.sin(s.ageInTicks * 0.2F) * 0.05F;
		legL2.xRot = dangle * 0.6F;
		legL3.xRot = -dangle * 0.5F;
		legR1.xRot = dangle + (float) Math.sin(s.ageInTicks * 0.2F + 1) * 0.05F;
		legR2.xRot = dangle * 0.6F;
		legR3.xRot = -dangle * 0.5F;
	}
}
